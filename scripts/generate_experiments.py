"""Generate real experiment reports for the knowledge assistant to index.

Trains a few scikit-learn models on datasets bundled with scikit-learn (no downloads),
and writes each result as a markdown report:

    corpus/experiments/exp-101-*.md ... exp-104-*.md
    corpus/docs/experiment-conventions.md

Every number in the reports is measured on the machine that runs this script, and the
verdict sentences are computed from those numbers, not written by hand. A few short
sentences of general background (for example what a smaller C means) are fixed text.

    python scripts/generate_experiments.py              # writes into ./corpus
    python scripts/generate_experiments.py --out /tmp/x # somewhere else

Fit times differ slightly on every run, so re-running changes exp-102 (the indexer will
then re-embed that file). Accuracy numbers are deterministic for a given seed and
scikit-learn version.
"""
import argparse
import platform
from datetime import date
from pathlib import Path

import sklearn
from sklearn.datasets import load_breast_cancer, load_digits
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold, cross_validate
from sklearn.neighbors import KNeighborsClassifier
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC
from sklearn.tree import DecisionTreeClassifier

SEED = 1234
FOLDS = 5
CV = StratifiedKFold(n_splits=FOLDS, shuffle=True, random_state=SEED)


# ---------- helpers ----------
def evaluate(model, X, y, metrics=("accuracy",)) -> dict:
    """5-fold CV. Returns {metric: (mean, std)} plus 'fit_time' (mean seconds per fold)."""
    res = cross_validate(model, X, y, cv=CV, scoring=list(metrics))
    out = {m: (res[f"test_{m}"].mean(), res[f"test_{m}"].std()) for m in metrics}
    out["fit_time"] = res["fit_time"].mean()
    return out


def pct(mean_std) -> str:
    m, s = mean_std
    return f"{m * 100:.1f} ± {s * 100:.1f}"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def verdict(scores: dict[str, tuple[float, float]], metric: str = "accuracy") -> str:
    """Compare the best two entries. Differences below one fold-std are called noise."""
    ranked = sorted(scores.items(), key=lambda kv: kv[1][0], reverse=True)
    (best, (b_mean, b_std)), (second, (s_mean, _)) = ranked[0], ranked[1]
    gap = (b_mean - s_mean) * 100
    text = f"Best {metric}: {best} ({b_mean * 100:.1f} ± {b_std * 100:.1f})."
    if gap < b_std * 100:
        return (text + f" The gap to {second} is {gap:.1f} points, smaller than the fold-to-fold "
                f"standard deviation ({b_std * 100:.1f}), so the two are not clearly different.")
    return (text + f" It beat {second} by {gap:.1f} points, more than the fold-to-fold "
            f"standard deviation ({b_std * 100:.1f}).")


def report(number: int, title: str, dataset: str, model_desc: str, header: list[str],
           rows: list[list[str]], conclusion: str, note: str = "") -> str:
    return f"""# Experiment {number}: {title}

## Setup
Dataset: {dataset}. Model: {model_desc}. Evaluation: stratified {FOLDS}-fold cross-validation,
shuffled, seed {SEED}. Scores are mean ± standard deviation across folds, in percentage points.
Run on {date.today().isoformat()} with scikit-learn {sklearn.__version__}, Python {platform.python_version()}.

## Results
{table(header, rows)}
{note}
## Conclusion
{conclusion}

## Reproducibility
Generated by `scripts/generate_experiments.py` (seed {SEED}). Accuracy is deterministic for a
given seed and scikit-learn version; fit times depend on the machine.
"""


# ---------- experiments ----------
def exp_101(digits) -> tuple[str, str]:
    X, y = digits
    scores, rows = {}, []
    for c in [0.001, 0.01, 0.1, 1, 10, 100]:
        model = make_pipeline(StandardScaler(), LogisticRegression(C=c, max_iter=2000))
        r = evaluate(model, X, y)
        scores[f"C={c}"] = r["accuracy"]
        rows.append([str(c), pct(r["accuracy"])])
    body = report(
        101, "Logistic regression regularization strength (C)",
        "scikit-learn digits (1797 samples, 64 features, 10 classes)",
        "StandardScaler + LogisticRegression (max_iter=2000), varying inverse regularization strength C",
        ["C", "accuracy (%)"], rows,
        verdict(scores) + " Smaller C means stronger regularization.")
    return "exp-101-logreg-regularization.md", body


def exp_102(digits) -> tuple[str, str]:
    X, y = digits
    scores, rows, times = {}, [], {}
    for n in [10, 50, 100, 300]:
        r = evaluate(RandomForestClassifier(n_estimators=n, random_state=SEED), X, y)
        scores[f"n_estimators={n}"] = r["accuracy"]
        times[n] = r["fit_time"]
        rows.append([str(n), pct(r["accuracy"]), f"{r['fit_time']:.2f}"])
    body = report(
        102, "Random forest size (n_estimators)",
        "scikit-learn digits (1797 samples, 64 features, 10 classes)",
        "RandomForestClassifier with default depth, varying the number of trees",
        ["n_estimators", "accuracy (%)", "fit time per fold (s)"], rows,
        verdict(scores) + f" Fit time per fold went from {times[10]:.2f} s with 10 trees to "
        f"{times[300]:.2f} s with 300 trees on this machine.",
        note="\nFit time is the mean seconds to train one fold on this machine; compare it only within this report.\n")
    return "exp-102-random-forest-size.md", body


def exp_103(digits) -> tuple[str, str]:
    X, y = digits
    models = {
        "Logistic regression (C=1, scaled)": make_pipeline(StandardScaler(), LogisticRegression(max_iter=2000)),
        "Random forest (100 trees)": RandomForestClassifier(n_estimators=100, random_state=SEED),
        "SVM (RBF kernel, scaled)": make_pipeline(StandardScaler(), SVC()),
        "k-nearest neighbours (k=5, scaled)": make_pipeline(StandardScaler(), KNeighborsClassifier()),
        "Decision tree": DecisionTreeClassifier(random_state=SEED),
    }
    scores, rows = {}, []
    for name, model in models.items():
        r = evaluate(model, X, y, metrics=("accuracy", "f1_macro"))
        scores[name] = r["accuracy"]
        rows.append([name, pct(r["accuracy"]), pct(r["f1_macro"])])
    body = report(
        103, "Model family comparison",
        "scikit-learn digits (1797 samples, 64 features, 10 classes)",
        "five classifiers with default hyperparameters unless noted",
        ["model", "accuracy (%)", "macro F1 (%)"], rows, verdict(scores))
    return "exp-103-model-comparison.md", body


def exp_104() -> tuple[str, str]:
    d = load_breast_cancer()
    X, y = d.data, d.target
    variants = {"no scaling": SVC(), "StandardScaler": make_pipeline(StandardScaler(), SVC())}
    scores, rows = {}, []
    for name, model in variants.items():
        r = evaluate(model, X, y)
        scores[name] = r["accuracy"]
        rows.append([name, pct(r["accuracy"])])
    body = report(
        104, "Effect of feature scaling on an RBF SVM",
        "scikit-learn breast cancer Wisconsin (569 samples, 30 features, 2 classes)",
        "SVC with RBF kernel, with and without StandardScaler",
        ["preprocessing", "accuracy (%)"], rows,
        verdict(scores) + " SVMs with an RBF kernel are sensitive to feature scale because the "
        "kernel depends on distances between samples.")
    return "exp-104-feature-scaling.md", body


CONVENTIONS = f"""# Experiment conventions

## Evaluation protocol
Every experiment uses stratified {FOLDS}-fold cross-validation with shuffling and seed {SEED}.
Reported scores are the mean and standard deviation across the {FOLDS} folds, in percentage points.
Runs without a fixed seed are not comparable.

## Metrics
Accuracy is the default metric. Macro F1 is added for multi-class model comparisons, because it
weights every class equally. Fit time is the mean seconds to train one fold. It depends on the
machine, so compare fit times only within a single report.

## Datasets
Two datasets bundled with scikit-learn are used, so no downloads are needed:
digits (1797 samples, 64 features, 10 classes) and breast cancer Wisconsin
(569 samples, 30 features, 2 classes).

## Interpreting differences
If the gap between the two best configurations is smaller than the fold-to-fold standard
deviation of the best one, the two are treated as not clearly different. Do not tune
hyperparameters on data you also report final results on.

## Reproducing
Run `python scripts/generate_experiments.py`. Accuracy is deterministic for a given seed and
scikit-learn version.
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="corpus", help="corpus folder to write into")
    out = Path(ap.parse_args().out)
    (out / "experiments").mkdir(parents=True, exist_ok=True)
    (out / "docs").mkdir(parents=True, exist_ok=True)

    digits = load_digits(return_X_y=True)
    for build in (lambda: exp_101(digits), lambda: exp_102(digits),
                  lambda: exp_103(digits), exp_104):
        name, body = build()
        (out / "experiments" / name).write_text(body, encoding="utf-8")
        print("wrote", out / "experiments" / name)
    (out / "docs" / "experiment-conventions.md").write_text(CONVENTIONS, encoding="utf-8")
    print("wrote", out / "docs" / "experiment-conventions.md")


if __name__ == "__main__":
    main()